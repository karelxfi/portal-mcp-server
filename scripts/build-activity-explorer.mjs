import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

import { build } from 'esbuild'

const root = process.cwd()
const output = path.join(root, 'src/generated/activity-explorer.generated.ts')
const versionOutput = path.join(root, 'src/generated/activity-explorer.version.ts')

const result = await build({
  entryPoints: [path.join(root, 'src/app-ui/index.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2022'],
  write: false,
  minify: true,
  treeShaking: true,
  legalComments: 'none',
  charset: 'utf8',
  sourcemap: false,
  define: { 'process.env.NODE_ENV': '"production"' },
})

const bundle = result.outputFiles[0]?.text ?? ''
if (!bundle) throw new Error('SQD Activity Explorer bundle is empty')
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="color-scheme" content="light dark"><title>SQD Blockchain Activity Explorer</title></head><body><div id="app"></div><script>${bundle}</script></body></html>`
const hash = createHash('sha256').update(html).digest('hex').slice(0, 12)
const bytes = Buffer.byteLength(html)
const maxBytes = 700_000
if (bytes > maxBytes)
  throw new Error(`SQD Activity Explorer is ${bytes} bytes, above the ${maxBytes}-byte release budget`)

await mkdir(path.dirname(output), { recursive: true })
await writeFile(
  output,
  `// Generated by scripts/build-activity-explorer.mjs.\nexport const ACTIVITY_EXPLORER_HTML = ${JSON.stringify(html)} as const\n`,
  'utf8',
)
await writeFile(
  versionOutput,
  `// Generated by scripts/build-activity-explorer.mjs.\nexport const ACTIVITY_EXPLORER_HASH = ${JSON.stringify(hash)} as const\nexport const ACTIVITY_EXPLORER_BYTES = ${bytes} as const\n`,
  'utf8',
)
console.log(`Built SQD Activity Explorer: ${bytes} bytes, hash ${hash}`)
