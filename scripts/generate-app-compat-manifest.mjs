import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const root = process.cwd()
const historyPath = path.join(root, 'config/app-resource-history.json')
const outputPath = path.join(root, 'src/apps/activity-explorer-compat.ts')
const history = JSON.parse(await readFile(historyPath, 'utf8'))

if (history.schemaVersion !== 1 || !Array.isArray(history.retained) || history.retained.length === 0) {
  throw new Error('App resource history must contain at least one retained v1 release entry')
}

const seenVersions = new Set()
const seenHashes = new Set()
for (const entry of history.retained) {
  if (!/^0\.8\.\d+$/.test(entry.version)) throw new Error(`Invalid retained release version: ${entry.version}`)
  if (!/^[a-f0-9]{12}$/.test(entry.hash)) throw new Error(`Invalid retained App hash for ${entry.version}`)
  if (seenVersions.has(entry.version)) throw new Error(`Duplicate retained release version: ${entry.version}`)
  if (seenHashes.has(entry.hash)) throw new Error(`Duplicate retained App hash: ${entry.hash}`)
  seenVersions.add(entry.version)
  seenHashes.add(entry.hash)
}

const annotatedHashes = history.retained.map((entry) => `  '${entry.hash}', // v${entry.version}`).join('\n')
const source =
  `// Generated by scripts/generate-app-compat-manifest.mjs from config/app-resource-history.json.\n` +
  `export const RETAINED_ACTIVITY_EXPLORER_HASHES = [\n${annotatedHashes}\n] as const\n\n` +
  `export const RETAINED_ACTIVITY_EXPLORER_RESOURCE_URIS = RETAINED_ACTIVITY_EXPLORER_HASHES.map(\n` +
  `  (hash) => \`ui://sqd/activity-explorer.\${hash}.html\`,\n` +
  `)\n`

await writeFile(outputPath, source, 'utf8')
console.log(`Generated ${history.retained.length} retained SQD App resource aliases`)
